export function withSkinLinks(g) {
  if (!LINK_TO.has(g.slug)) return g;
  const body = [...g.body];
  let at = body.findIndex((b) => b.type === 'faq');
  if (at === -1) at = body.length;
  else if (at > 0 && body[at - 1].type === 'h2') at -= 1; // keep the FAQ heading with its FAQ
  body.splice(at, 0, MORE);
  return { ...g, body };
}
