export function withNameLinks(g) {
  const text = EXTRA[g.slug];
  if (!text) return g;
  const body = [...g.body];
  let at = body.findIndex((b) => b.type === 'faq');
  if (at === -1) at = body.length;
  else if (at > 0 && body[at - 1].type === 'h2') at -= 1;
  body.splice(at, 0, { type: 'p', text });
  return { ...g, body };
}
